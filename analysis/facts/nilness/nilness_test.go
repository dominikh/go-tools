func TestNilness(t *testing.T) {
	analysistest.Run(t, analysistest.TestData(), Analysis, "example.com/...")
}

func TestLargeGeneratedStateMachine(t *testing.T) {
	dir := t.TempDir()
	pkg := filepath.Join(dir, "src", "generated")
	if err := os.MkdirAll(pkg, 0o755); err != nil {
		t.Fatal(err)
	}

	source := "// Code generated by TestLargeGeneratedStateMachine. DO NOT EDIT.\n" +
		"package generated\n\n" +
		"func stateMachine(x int) *int {\n" +
		strings.Repeat("\tif x&1 == 0 { x++ }\n", 1001) +
		"\treturn &x\n}\n"
	if err := os.WriteFile(filepath.Join(pkg, "generated.go"), []byte(source), 0o644); err != nil {
		t.Fatal(err)
	}

	analysistest.Run(t, dir, Analysis, "generated")
}
