package generated

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestIsGeneratedOnlyChecksFileHeader(t *testing.T) {
	tests := []struct {
		name string
		text string
		want bool
	}{
		{
			name: "long license header",
			text: strings.Repeat("// license\n", 20) + "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage p\n",
			want: true,
		},
		{
			name: "indented package clause",
			text: "  package p\n// Code generated by protoc-gen-go. DO NOT EDIT.\n",
			want: false,
		},
		{
			name: "marker inside block comment",
			text: "/*\n// Code generated by protoc-gen-go. DO NOT EDIT.\n*/\npackage p\n",
			want: false,
		},
		{
			name: "old cgo header",
			text: "// Created by cgo - DO NOT EDIT\npackage p\n",
			want: true,
		},
		{
			name: "header",
			text: "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage p\n",
			want: true,
		},
		{
			name: "body comment",
			text: "package p\n\nfunc f() {\n\t// Code generated by protoc-gen-go. DO NOT EDIT.\n}\n",
			want: false,
		},
		{
			name: "late comment",
			text: "package p\n\n// Code generated by protoc-gen-go. DO NOT EDIT.\n",
			want: false,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			path := filepath.Join(t.TempDir(), "generated.go")
			if err := os.WriteFile(path, []byte(tt.text), 0o600); err != nil {
				t.Fatal(err)
			}
			_, got := isGenerated(path)
			if got != tt.want {
				t.Fatalf("isGenerated() = %v, want %v", got, tt.want)
			}
		})
	}
}
